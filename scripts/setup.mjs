#!/usr/bin/env node
// Setup & health check for this site. Run it after installing, after changing
// settings, and before you hand a site to a customer.
//
//   node scripts/setup.mjs               check everything (needs .env.local)
//   node scripts/setup.mjs --env FILE    read a different env file
//   node scripts/setup.mjs build-sql     regenerate supabase/setup.sql from schema.sql + security-lockdown.sql
//
// It never changes your database. It reads it, compares it with supabase/schema.sql,
// and tells you what to fix. Exit code 1 if anything is broken (usable in CI).
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const args = process.argv.slice(2)
const envFile = args.includes('--env') ? args[args.indexOf('--env') + 1] : join(ROOT, '.env.local')

// ------------------------------------------------------------------ build-sql
const SETUP_HEADER = `-- =====================================================================
-- FULL SETUP FOR A NEW SITE — paste this whole file into the Supabase SQL
-- editor and run it ONCE. It builds every table, then locks the database down
-- so the public key can only read what the public site shows.
--
-- (Generated by \`node scripts/setup.mjs build-sql\` from schema.sql +
--  security-lockdown.sql — edit those, not this.)
-- =====================================================================

`
const SETUP_MIDDLE = `\n\n-- =====================================================================
-- PART 2: SECURITY LOCKDOWN
-- =====================================================================

`
function buildSetupSql() {
  const schema = readFileSync(join(ROOT, 'supabase/schema.sql'), 'utf8')
  const lock = readFileSync(join(ROOT, 'supabase/security-lockdown.sql'), 'utf8')
  return SETUP_HEADER + schema + SETUP_MIDDLE + lock
}
if (args[0] === 'build-sql') {
  writeFileSync(join(ROOT, 'supabase/setup.sql'), buildSetupSql())
  console.log('Wrote supabase/setup.sql')
  process.exit(0)
}

// ------------------------------------------------------------------ output helpers
const useColor = process.stdout.isTTY && !process.env.NO_COLOR
const paint = (c, s) => (useColor ? `\x1b[${c}m${s}\x1b[0m` : s)
const results = { ok: 0, warn: 0, fail: 0 }
function line(kind, label, hint) {
  results[kind]++
  const mark = kind === 'ok' ? paint(32, '✓') : kind === 'warn' ? paint(33, '!') : paint(31, '✗')
  console.log(`  ${mark} ${label}`)
  if (hint && kind !== 'ok') for (const h of [].concat(hint)) console.log(`      ${paint(2, '→')} ${h}`)
}
const ok = (l) => line('ok', l), warn = (l, h) => line('warn', l, h), fail = (l, h) => line('fail', l, h)
const section = (t) => console.log(`\n${paint(1, t)}`)

// ------------------------------------------------------------------ env
function parseEnv(text) {
  const out = {}
  for (const raw of text.split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(raw)
    if (!m || raw.trim().startsWith('#')) continue
    let v = m[2]
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1)
    else v = v.replace(/\s+#.*$/, '')
    out[m[1]] = v
  }
  return out
}
let fileEnv = {}
const envFound = existsSync(envFile)
if (envFound) fileEnv = parseEnv(readFileSync(envFile, 'utf8'))
const env = (k) => (process.env[k] !== undefined && process.env[k] !== '' ? process.env[k] : fileEnv[k] || '')

function keyRole(key) {
  if (key.startsWith('sb_secret_')) return 'service_role'
  if (key.startsWith('sb_publishable_')) return 'anon'
  try { return JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString('utf8')).role || 'unknown' } catch { return 'unknown' }
}

console.log(paint(1, 'Site setup check'))
console.log(paint(2, `project: ${ROOT}`))

// ================================================================== 1. environment
section('1. Environment')
const nodeMajor = Number(process.versions.node.split('.')[0])
nodeMajor >= 18 ? ok(`Node ${process.versions.node}`) : fail(`Node ${process.versions.node} is too old`, 'Install Node 18 or newer (https://nodejs.org).')

if (!envFound && !process.env.NEXT_PUBLIC_SUPABASE_URL) {
  fail(`No env file found at ${envFile}`, ['Copy .env.example to .env.local and fill it in.', 'On Vercel, set the same variables under Settings -> Environment Variables and run this check locally with --env.'])
} else if (envFound) ok(`Read ${envFile.replace(ROOT, '.')}`)

const URL_ = env('NEXT_PUBLIC_SUPABASE_URL').replace(/\/+$/, '')
const ANON = env('NEXT_PUBLIC_SUPABASE_ANON_KEY')
const SVC = env('SUPABASE_SERVICE_ROLE_KEY')
let urlOk = false
if (!URL_) fail('NEXT_PUBLIC_SUPABASE_URL is not set', 'Supabase -> Project Settings -> API -> Project URL.')
else {
  try {
    const u = new URL(URL_)
    urlOk = true
    if (/^(localhost|127\.0\.0\.1)/.test(u.hostname)) ok(`Supabase URL: ${u.host} (local)`)
    else if (u.protocol !== 'https:') warn(`Supabase URL is not https: ${URL_}`)
    else if (!/supabase\.(co|in)$/.test(u.hostname)) warn(`Supabase URL is not a supabase.co address: ${u.host}`, 'Fine if you use a custom domain; otherwise double-check it.')
    else ok(`Supabase URL: ${u.host}`)
  } catch { fail(`NEXT_PUBLIC_SUPABASE_URL is not a valid URL: ${URL_}`) }
}

let keysOk = false
let keyProblem = false // true when the keys are swapped/identical — later checks would be misleading
if (!ANON) fail('NEXT_PUBLIC_SUPABASE_ANON_KEY is not set', 'Use the key labelled "anon" / "public" (or "Publishable key").')
if (!SVC) fail('SUPABASE_SERVICE_ROLE_KEY is not set', ['Use the key labelled "service_role" / "secret". Server-only — never prefix it NEXT_PUBLIC_.', 'Without it every admin save and every order fails.'])
if (ANON && SVC) {
  const ra = keyRole(ANON), rs = keyRole(SVC)
  if (ra === 'service_role') keyProblem = true
  if (rs === 'anon') keyProblem = true
  if (ra === 'service_role') fail('The PUBLIC key is actually the SECRET service_role key', ['NEXT_PUBLIC_SUPABASE_ANON_KEY ships to every visitor\'s browser. A secret key there gives anyone full control of your database.', 'Put the "anon"/"public" key there, and rotate the service_role key in Supabase (it is now exposed).'])
  else if (rs === 'anon') fail('The service key is actually the public anon key', 'SUPABASE_SERVICE_ROLE_KEY must be the "service_role"/"secret" key.')
  else if (ra === 'anon' && rs === 'service_role') { ok('Public and secret keys are the right way round'); keysOk = true }
  else warn(`Could not confirm the key types (public: ${ra}, secret: ${rs})`, 'Double-check you did not swap them.')
}
if (ANON && SVC && ANON === SVC) { keyProblem = true; fail('The public and secret keys are identical') }

const secret = env('NEXTAUTH_SECRET')
if (!secret) fail('NEXTAUTH_SECRET is not set', 'Generate one:  openssl rand -base64 32   (or any long random string)')
else if (secret.length < 32 || /dummy|changeme|secret|example|test/i.test(secret)) warn('NEXTAUTH_SECRET looks weak or like a placeholder', 'Use a long random value (32+ characters). It signs your admin login cookie.')
else ok('NEXTAUTH_SECRET is set')
env('NEXTAUTH_URL') ? ok(`NEXTAUTH_URL: ${env('NEXTAUTH_URL')}`) : warn('NEXTAUTH_URL is not set', 'Set it to your site\'s public address (http://localhost:3000 locally).')

const hash = env('ADMIN_PASSWORD_HASH'), plain = env('ADMIN_PASSWORD')
if (hash) {
  /^scrypt:\d+:\d+:\d+:[\w-]+:[\w-]+$/.test(hash) ? ok('Admin password is stored as a hash') : fail('ADMIN_PASSWORD_HASH is malformed', 'Regenerate it:  node scripts/admin-setup.mjs hash')
} else if (plain) {
  warn('Admin password is stored in plain text (ADMIN_PASSWORD)', 'Switch:  node scripts/admin-setup.mjs hash  ->  set ADMIN_PASSWORD_HASH  ->  delete ADMIN_PASSWORD.')
  if (plain.length < 12) warn(`ADMIN_PASSWORD is only ${plain.length} characters`, 'Use a long passphrase (12+ characters).')
} else fail('No admin password configured', ['Admin login is refused until one is set.', 'Run:  node scripts/admin-setup.mjs hash'])
env('ADMIN_TOTP_SECRET') ? ok('Two-factor login is ON') : warn('Two-factor login is OFF', 'Recommended:  node scripts/admin-setup.mjs totp')

env('RESEND_API_KEY') ? ok('Email (Resend) key is set') : warn('RESEND_API_KEY is not set', 'Order, contact and newsletter emails will NOT be sent. Orders are still saved.')
env('NOTIFY_TO_EMAIL') ? ok(`Notifications go to ${env('NOTIFY_TO_EMAIL')}`) : warn('NOTIFY_TO_EMAIL is not set', 'You will not be emailed about new orders or contact messages.')

// ================================================================== 2. configuration
section('2. Site configuration')
const cfgPath = join(ROOT, 'site.config.ts')
if (!existsSync(cfgPath)) fail('site.config.ts is missing')
else {
  const cfg = readFileSync(cfgPath, 'utf8')
  const name = /const name = '([^']*)'/.exec(cfg)?.[1]
  const siteUrl = env('NEXT_PUBLIC_SITE_URL') || /\|\| '(https?:[^']*)'/.exec(cfg)?.[1] || ''
  ok(`Site name: ${name || '(unknown)'}`)
  ok(`Site URL: ${siteUrl || '(unknown)'}`)
  const r = spawnSync(process.execPath, [join(ROOT, 'scripts/check-personalization.mjs')], { encoding: 'utf8' })
  const m = /(\d+) code file\(s\), (\d+) content file\(s\)/.exec(r.stdout || '')
  if (m) {
    Number(m[1]) === 0 ? ok('No personal details hardcoded outside site.config.ts') : warn(`${m[1]} code file(s) still contain the original owner's details`, 'Run:  node scripts/check-personalization.mjs')
    Number(m[2]) > 0 && warn(`${m[2]} page(s) still contain the original owner's own writing`, 'Rewrite them — see PERSONALIZE.md (about, tech-stack, resume placeholders).')
  }
}

// ================================================================== 3. database
section('3. Database')
async function api(path, key, opts = {}) {
  const ctl = new AbortController(); const t = setTimeout(() => ctl.abort(), 10000)
  try {
    const res = await fetch(`${URL_}${path}`, { headers: { apikey: key, Authorization: `Bearer ${key}`, ...(opts.headers || {}) }, method: opts.method || 'GET', body: opts.body, signal: ctl.signal })
    const text = await res.text(); let json = null; try { json = JSON.parse(text) } catch { /* not json */ }
    return { status: res.status, json, text }
  } catch (e) { return { status: 0, json: null, text: String(e?.cause?.code || e?.message || e) } } finally { clearTimeout(t) }
}

// What the code expects: parsed from supabase/schema.sql
function parseSchema() {
  const sql = readFileSync(join(ROOT, 'supabase/schema.sql'), 'utf8'); const tables = {}
  for (const m of sql.matchAll(/create table if not exists (\w+) \(\n([\s\S]*?)\n\);/g)) {
    const cols = new Set()
    for (const l of m[2].split('\n')) { const c = /^\s+(\w+)\s+\S/.exec(l); if (c && !/^(constraint|primary|unique|check|foreign)$/i.test(c[1])) cols.add(c[1]) }
    tables[m[1]] = cols
  }
  for (const m of sql.matchAll(/alter table (\w+) add column if not exists (\w+)/g)) (tables[m[1]] ||= new Set()).add(m[2])
  return tables
}

let dbReachable = false
if (keyProblem) warn('Skipping database checks', 'Fix the key problem above first — results with the wrong key would be misleading.')
else if (!urlOk || !SVC) warn('Skipping database checks', 'Fix the environment problems above first.')
else {
  const ping = await api('/rest/v1/', SVC)
  if (ping.status === 0) fail(`Cannot reach ${URL_}`, [`Network error: ${ping.text}`, 'Check the URL and your internet connection.'])
  else if (ping.status === 401 || ping.status === 403) fail('The database rejected the service key', 'Check SUPABASE_SERVICE_ROLE_KEY belongs to THIS project (and was copied whole).')
  else if (ping.status >= 400) fail(`The database answered HTTP ${ping.status}`, ping.text.slice(0, 150))
  else { ok('Connected to the database with the service key'); dbReachable = true }
}

if (dbReachable) {
  const expected = parseSchema(); const names = Object.keys(expected).sort()
  const missingTables = [], missingCols = {}, inspectErrors = []
  await Promise.all(names.map(async (t) => {
    let cols = [...expected[t]]
    for (let round = 0; round < 40; round++) {
      const r = await api(`/rest/v1/${t}?select=${cols.join(',')}&limit=0`, SVC)
      if (r.status >= 200 && r.status < 300) return
      const code = r.json?.code, msg = r.json?.message || ''
      if (code === 'PGRST205' || code === '42P01' || (r.status === 404 && !code)) { missingTables.push(t); return }
      const col = /column [\w.]*?(\w+) does not exist/.exec(msg)?.[1] || /find the '(\w+)' column/.exec(msg)?.[1]
      if (col && cols.includes(col)) { (missingCols[t] ||= []).push(col); cols = cols.filter((c) => c !== col); continue }
      inspectErrors.push({ t, status: r.status, msg: (msg || r.text).slice(0, 120) }); return
    }
  }))
  if (inspectErrors.length) {
    const statuses = new Set(inspectErrors.map((e) => e.status))
    if (inspectErrors.length >= 3 && statuses.size === 1) {
      const e = inspectErrors[0]
      fail(`The service key cannot read ${inspectErrors.length} of your tables (HTTP ${e.status})`, [e.msg, e.status === 401 || e.status === 403 ? 'The service key may belong to a different project, or its role was changed.' : 'Check the Supabase project is running.'])
    } else for (const e of inspectErrors) fail(`Could not inspect table "${e.t}"`, `HTTP ${e.status}: ${e.msg}`)
  }
  const fixHint = ['New site: run supabase/setup.sql in the Supabase SQL editor.', 'Existing site: run supabase/schema.sql (it only adds what is missing, and never changes or removes data).']
  if (missingTables.length) fail(`${missingTables.length} table(s) missing: ${missingTables.sort().join(', ')}`)
  const colTables = Object.keys(missingCols).sort()
  for (const t of colTables) fail(`Table "${t}" is missing column(s): ${missingCols[t].join(', ')}`)
  if (missingTables.length || colTables.length) for (const h of fixHint) console.log(`      ${paint(2, '→')} ${h}`)
  if (!missingTables.length && !colTables.length && !inspectErrors.length) {
    const colCount = names.reduce((n, t) => n + expected[t].size, 0)
    ok(`All ${names.length} tables and ${colCount} columns the site needs are present`)
    const s = await api('/rest/v1/site_settings?select=id&id=eq.1', SVC)
    Array.isArray(s.json) && s.json.length === 1 ? ok('Site settings row exists') : fail('Site settings row (id = 1) is missing', 'Run supabase/schema.sql — it inserts it.')
  }

  const b = await api('/storage/v1/bucket', SVC)
  if (b.status === 200 && Array.isArray(b.json)) {
    for (const want of ['blog-images', 'resume-images']) {
      const f = b.json.find((x) => x.name === want || x.id === want)
      !f ? fail(`Storage bucket "${want}" is missing`, 'Run supabase/schema.sql (it creates both), or create it in Supabase -> Storage and mark it Public.')
        : f.public ? ok(`Storage bucket "${want}" exists and is public`) : warn(`Storage bucket "${want}" is not public`, 'Images will not show on the site. Supabase -> Storage -> the bucket -> make it Public.')
    }
  } else warn('Could not check storage buckets', `HTTP ${b.status}. Make sure "blog-images" and "resume-images" exist and are Public.`)
}

// ================================================================== 4. security
section('4. Security (tested the way an outsider would: with the public key only)')
if (!dbReachable || !ANON || !keysOk) warn('Skipping the lockdown test', 'It needs a working database connection and correctly-typed keys.')
else {
  const r = spawnSync(process.execPath, [join(ROOT, 'scripts/verify-lockdown.mjs')], { encoding: 'utf8', env: { ...process.env, SUPABASE_URL: URL_, SUPABASE_ANON_KEY: ANON } })
  const res = /RESULT: (\d+) passed, (\d+) failed/.exec(r.stdout || '')
  if (res && Number(res[2]) === 0) ok(`Database is locked down (${res[1]} of ${res[1]} attack checks blocked or passed)`)
  else if (res) {
    fail(`Database is NOT properly locked down (${res[2]} check(s) failed)`, ['Run supabase/security-lockdown.sql (included in setup.sql).', 'Details:  node scripts/verify-lockdown.mjs'])
    for (const l of (r.stdout || '').split('\n').filter((x) => x.startsWith('FAIL')).slice(0, 4)) console.log(`        ${l}`)
  } else fail('Could not run the lockdown test', (r.stdout || r.stderr || '').slice(0, 200))
}

// the generated setup.sql must match its sources
section('5. Repository')
try {
  const current = readFileSync(join(ROOT, 'supabase/setup.sql'), 'utf8')
  current === buildSetupSql() ? ok('supabase/setup.sql is up to date') : warn('supabase/setup.sql is out of date', 'Run:  node scripts/setup.mjs build-sql')
} catch { warn('supabase/setup.sql not found', 'Run:  node scripts/setup.mjs build-sql') }

// ================================================================== summary
console.log(`\n${paint(1, 'Summary:')} ${paint(32, `${results.ok} OK`)}, ${paint(33, `${results.warn} to review`)}, ${paint(31, `${results.fail} to fix`)}`)
console.log(results.fail ? paint(31, 'Not ready — fix the ✗ items above, then run this again.') : results.warn ? paint(33, 'Working. Review the ! items before going live.') : paint(32, 'Everything checks out.'))
process.exit(results.fail ? 1 : 0)
